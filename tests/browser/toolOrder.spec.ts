import { test, expect } from "@playwright/test";
const defaults = ["Currency", "Weight", "Dimensions", "Cubic feet / CBM", "Length", "Product specs", "Time zones", "Volume", "Temperature"];
test("personal order persists across pages, controls home shortcuts and can be reset", async ({page}) => {
  await page.goto("/");
  const nav = page.getByRole("navigation", {name: "Conversion tools"}).getByRole("link");
  await expect(nav.locator("span:nth-child(2)")).toHaveText(defaults);
  await expect(page.locator('.quick-start a strong')).toHaveText(defaults.slice(0, 3));
  await page.locator(".tool-order > summary").click();
  await expect(page.getByRole("button", {name: "Move Currency up", exact: true})).toBeDisabled();
  await expect(page.getByRole("button", {name: "Move Temperature down", exact: true})).toBeDisabled();
  await page.getByRole("button", {name: "Move Weight up", exact: true}).click();
  await expect(nav.locator("span:nth-child(2)")).toHaveText(["Weight", "Currency", ...defaults.slice(2)]);
  await expect(page.locator('.quick-start a strong')).toHaveText(["Weight", "Currency", "Dimensions"]);
  await page.getByRole("button", {name: "切换到中文"}).click();
  await expect(page.getByRole("navigation").getByRole("link").first()).toHaveAccessibleName("重量");
  await page.getByRole("navigation").getByRole("link", {name: "长度", exact: true}).click();
  await expect(page.getByRole("navigation").getByRole("link").first()).toHaveAccessibleName("重量");
  await page.reload();
  await expect(page.getByRole("navigation").getByRole("link").first()).toHaveAccessibleName("重量");
  await page.locator(".tool-order > summary").click();
  await page.getByRole("button", {name: "恢复默认排序", exact: true}).click();
  await expect(page.getByRole("navigation").getByRole("link").first()).toHaveAccessibleName("汇率");
  await page.reload();
  await expect(page.getByRole("navigation").getByRole("link").first()).toHaveAccessibleName("汇率");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
